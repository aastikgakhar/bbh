"""Tooling-block detection. A blocked exchange is `inconclusive`, never a negative.

Per evidence-rules.md: a standing 403 on the scripted client while the browser
works, status 0, connection resets, HTTP/2-vs-HTTP/1.1 mismatches and silent
throttles are tooling artefacts. bbh records them; it never tries to evade them.
Stdlib only.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .httpraw import Exchange

# (label, status codes, body regex, header name that must be present or None)
SIGNATURES = [
    ("cloudflare", (403, 429, 503), r"Attention Required! \| Cloudflare|Sorry, you have been blocked|cf-error-details|Just a moment\.\.\.|cf-chl-", None),
    ("akamai", (403,), r"Access Denied.*Reference #|errors\.edgesuite\.net", None),
    ("aws-waf", (403,), r"Request blocked\.?|The request could not be satisfied", None),
    ("imperva", (403,), r"Incapsula incident|_Incapsula_Resource|Request unsuccessful\. Incapsula", None),
    ("sucuri", (403,), r"Sucuri WebSite Firewall|Access Denied - Sucuri", None),
    ("f5", (200, 403), r"The requested URL was rejected\. Please consult with your administrator", None),
    ("modsecurity", (403, 406), r"Mod_?Security|This error was generated by Mod_Security", None),
    ("datadome", (403,), r"datadome|dd\.js", None),
    ("perimeterx", (403,), r"_pxCaptcha|px-captcha|PerimeterX", None),
    ("captcha", (200, 403, 429), r"g-recaptcha|h-captcha|cf-turnstile|captcha-delivery", None),
    # the proxy's OWN error/interstitial page (it could not reach the target: wrong scheme, DNS,
    # TLS, connection refused). Burp serves it as 200, so without this it reads as a real response.
    ("burp-error", (200, 502, 504), r"<title>Burp Suite</title>|Burp Suite.{0,80}(failed|error|could not|unable to|cannot)|InterceptionHandler|burpsuite", None),
    ("proxy-error", (200, 502, 503, 504), r"(Zscaler|Squid|mitmproxy|Fiddler|Charles Proxy).{0,120}(error|failed|denied|blocked)", None),
]


@dataclass
class BlockVerdict:
    blocked: bool
    reason: str = ""
    throttle: bool = False  # back off before the next send
    retry_after_s: float | None = None


def detect(ex: Exchange, *, browser_baseline_status: int | None = None, http_version_hint: str | None = None) -> BlockVerdict:
    if ex.response is None:
        err = ex.error or "no response"
        if re.search(r"protocol|RST_STREAM|stream reset|h2|HTTP/2", err, re.I):
            return BlockVerdict(True, f"protocol error ({err}); the captured request used {http_version_hint or 'an unknown protocol'}: rerun with the matching HTTP version")
        return BlockVerdict(True, f"transport failure: {err}", throttle=bool(re.search(r"reset|refused|timed? ?out|EOF", err, re.I)))
    status = ex.status
    if status == 0:
        return BlockVerdict(True, "status 0 from the client (a local throttle, not a server answer)", throttle=True)
    if status == 429:
        ra = None
        h = ex.response.header("Retry-After")
        if h and h.strip().isdigit():
            ra = float(h.strip())
        return BlockVerdict(True, "429 Too Many Requests", throttle=True, retry_after_s=ra)
    body = ex.body_text[:20000]
    for label, codes, rx, _ in SIGNATURES:
        if status in codes and re.search(rx, body, re.I | re.S):
            return BlockVerdict(True, f"{label} block page (status {status})", throttle=True)
    if status == 403 and browser_baseline_status is not None and 200 <= browser_baseline_status < 300:
        return BlockVerdict(True, f"403 on the scripted client while the browser-captured request returned {browser_baseline_status}; rerun through the browser route", throttle=True)
    if status in (502, 503, 504) and len(body) < 2000:
        return BlockVerdict(True, f"{status} from an upstream or gateway", throttle=True)
    return BlockVerdict(False)
